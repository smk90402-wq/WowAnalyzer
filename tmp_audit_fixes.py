def rep(obj, key_path, old, new, tag):
    """dict/list 경로의 문자열 치환 (없으면 경고)."""
    cur = obj
    for k in key_path[:-1]:
        cur = cur[k]
    last = key_path[-1]
    s = cur[last]
    if old not in s:
        print(f"⚠ 못 찾음 [{tag}]: {old[:50]}")
        return
    cur[last] = s.replace(old, new)
    fixed.append(tag)


